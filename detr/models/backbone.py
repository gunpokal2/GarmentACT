class Backbone(BackboneBase):
    """ResNet backbone with frozen BatchNorm."""
    def __init__(self, name: str, # 'resnet18'
                 train_backbone: bool, # True
                 return_interm_layers: bool, # False
                 dilation: bool): # False
        backbone = getattr(torchvision.models, name)( # torchvision.models.resnet18
            replace_stride_with_dilation=[False, False, dilation],
            pretrained=is_main_process(), norm_layer=FrozenBatchNorm2d) # is_main_process() = True # pretrained # TODO do we want frozen batch_norm??
        num_channels = 512 if name in ('resnet18', 'resnet34') else 2048
        super().__init__(backbone, train_backbone, num_channels, return_interm_layers)


class Joiner(nn.Sequential):
    def __init__(self, backbone, position_embedding):
        super().__init__(backbone, position_embedding)
    # backbone과 position_embedding을 하나의 module chain으로 묶는다... self[0] = backbone, self[1] = position_embedding
    def forward(self, tensor_list: NestedTensor):
        xs = self[0](tensor_list) # xs['0'] (B, 512, 15, 20), BackboneBase의 forward로 들어감..., layer4에서 나온 feature return 
        out: List[NestedTensor] = []
        pos = []
        for name, x in xs.items():
            out.append(x)
            # position encoding
            pos.append(self[1](x).to(x.dtype)) # x shape에 대응되는 positional embedding return

        return out, pos # len(out) = 1, len(pos) = 1, out[0] (B, 512, 15, 20), pos[0] (1, 512, 15, 20)


def build_backbone(args):
    position_embedding = build_position_encoding(args) # detr/models/position_encoding.py
    train_backbone = args.lr_backbone > 0 # True, 1e-05
    return_interm_layers = args.masks # False
    backbone = Backbone(args.backbone, train_backbone, return_interm_layers, args.dilation) # args.backbone = 'resnet18', args.dilation = False
    model = Joiner(backbone, position_embedding) # backbone + position_embedding
    model.num_channels = backbone.num_channels # 512
    return model

